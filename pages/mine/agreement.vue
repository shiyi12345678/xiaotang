	const TAB_ORDER = ['agreement', 'privacy', 'jobinfo', 'safety']

	export default {
		data() {
			return {
				docs: DOCS,
				currentKey: 'agreement',
				tabs: TAB_ORDER.map(key => ({ key, title: DOCS[key].title }))
			}
		},
		computed: {
			doc() {
				return this.docs[this.currentKey] || this.docs.agreement
			}
		},
		onLoad(options) {
			const type = (options && options.type) || ''
			// 未知 type 一律回退到用户服务协议（本页四个 type 都由本地跳转传入，不做错误提示）
			if (this.docs[type]) this.currentKey = type
			uni.setNavigationBarTitle({ title: this.doc.title })
		},
		methods: {
			onSwitch(key) {
				if (!this.docs[key] || key === this.currentKey) return
				this.currentKey = key
				uni.setNavigationBarTitle({ title: this.doc.title })
				// 切换文档后回到页首，否则用户会停在上一篇的中间位置而误以为内容没变
				uni.pageScrollTo({ scrollTop: 0, duration: 200 })
			}
		}
	}
</script>

